package ast

import (
	"go/ast"
	"io"
)

// Ast 定义了 AST（抽象语法树）操作的标准接口，采用模板方法模式设计
//
// 设计理念：
// 1. 统一操作流程：定义了 AST 操作的完整生命周期（解析 -> 注入 -> 格式化 -> 可选回滚）
// 2. 多态性支持：不同的实现可以有不同的注入策略，但遵循相同的操作流程
// 3. 代码复用：通过 Base 结构体提供默认实现，子类只需实现特定的 Injection 逻辑
// 4. 类型安全：接口约束确保所有实现都提供必要的方法，编译时检查而非运行时错误
//
// 为什么使用接口而不是直接使用结构体？
// 1. 解耦合：调用方依赖接口而非具体实现，降低耦合度，提高代码灵活性
// 2. 可测试性：可以轻松创建 Mock 实现进行单元测试
// 3. 扩展性：新增 AST 操作类型只需实现此接口，无需修改现有代码（开闭原则）
// 4. 多态性：同一段代码可以处理不同类型的 AST 操作器，提高代码复用性
//
// 架构优势：
// - 模板方法模式：定义了操作流程的骨架，具体步骤由子类实现
// - 策略模式：不同的实现代表不同的代码注入策略
// - 组合优于继承：通过嵌入 Base 结构体实现代码复用，而非使用继承
//
// 使用场景：
// - PackageEnter: 模块化入口，注入包导入和结构体字段
// - PluginInitializeV2: 插件初始化，注入插件注册代码
// - 其他 AST 操作器：各种代码生成和代码注入场景
//
// 典型使用流程：
//  1. Parse: 解析源文件，获取 AST 文件节点
//  2. Injection: 向 AST 中注入新的代码节点（这是每个实现的核心逻辑）
//  3. Format: 将修改后的 AST 格式化并写回文件
//  4. Rollback: 可选的回滚操作，撤销之前的注入（通常为空实现）
//
// 好处总结：
//   - 统一性：所有 AST 操作都遵循相同的接口，便于理解和维护
//   - 可扩展性：新增操作类型只需实现接口，无需修改调用方代码
//   - 可测试性：接口便于 Mock，提高单元测试覆盖率
//   - 代码复用：Base 提供通用实现，子类只需关注核心逻辑
//   - 类型安全：编译时检查，避免运行时错误
type Ast interface {
	// Parse 解析 Go 源文件并返回 AST 文件节点
	//
	// 参数说明：
	//   - filename: 要解析的文件路径（绝对路径或相对路径）
	//   - writer: 可选的 io.Writer，用于从内存中读取源码（通常为 nil，表示从文件读取）
	//
	// 返回值：
	//   - file: 解析后的 AST 文件节点，包含完整的语法树结构
	//   - err: 解析过程中的错误信息
	//
	// 设计意图：
	//   - 统一的解析入口，所有 AST 操作都使用相同的解析逻辑
	//   - 支持从文件系统或内存读取源码，提高灵活性
	//   - 保留注释信息（通过 parser.ParseComments），确保代码生成不丢失重要信息
	//
	// 好处：
	//   - 代码复用：Base 提供默认实现，子类可以按需重写
	//   - 统一错误处理：所有解析错误都通过统一的方式处理
	//   - 灵活性：支持多种源码输入方式（文件、内存等）
	Parse(filename string, writer io.Writer) (file *ast.File, err error)

	// Rollback 回滚操作，用于撤销 Injection 所做的修改
	//
	// 参数说明：
	//   - file: 要回滚的 AST 文件节点
	//
	// 返回值：
	//   - err: 回滚过程中的错误信息
	//
	// 设计意图：
	//   - 提供撤销机制，允许回退代码注入操作
	//   - 保持接口完整性，即使某些实现不需要回滚功能
	//
	// 为什么大多数实现是空操作？
	//   - 很多 AST 操作是单向的（如代码生成），不需要回滚
	//   - 空实现避免了强制子类实现不必要的逻辑
	//   - 需要回滚的子类可以重写此方法实现具体逻辑
	//
	// 好处：
	//   - 接口统一：所有 AST 操作器都实现相同的方法签名
	//   - 扩展性：未来需要回滚功能时，只需实现此方法即可
	//   - 可选性：不需要回滚的实现可以保持空实现，减少代码量
	Rollback(file *ast.File) error

	// Injection 注入操作，用于向 AST 中注入新的代码节点
	//
	// 参数说明：
	//   - file: 要注入代码的 AST 文件节点（会被修改）
	//
	// 返回值：
	//   - err: 注入过程中的错误信息
	//
	// 设计意图：
	//   - 这是每个 AST 操作器的核心方法，实现具体的代码注入逻辑
	//   - 通过修改 AST 节点而非字符串拼接，保证生成的代码语法正确
	//   - 支持各种注入场景：导入包、添加结构体字段、注入函数调用等
	//
	// 为什么是接口的核心方法？
	//   - 注入逻辑是每个实现的核心差异点，各不相同
	//   - 强制子类实现此方法，确保功能完整性
	//   - 通过多态性，同一接口可以支持不同的注入策略
	//
	// 典型注入场景：
	//   - 添加 import 语句
	//   - 向结构体添加字段
	//   - 在函数中注入函数调用
	//   - 添加新的类型定义
	//
	// 好处：
	//   - 类型安全：通过 AST 操作而非字符串拼接，保证语法正确
	//   - 灵活性：不同的实现可以实现不同的注入策略
	//   - 可维护性：代码注入逻辑集中在一个方法中，便于理解和维护
	Injection(file *ast.File) error

	// Format 格式化输出，将修改后的 AST 格式化并写入文件或 Writer
	//
	// 参数说明：
	//   - filename: 输出文件路径（当 writer 为 nil 时使用）
	//   - writer: 可选的 io.Writer，如果提供则写入到 writer，否则写入到文件
	//   - file: 要格式化的 AST 文件节点
	//
	// 返回值：
	//   - err: 格式化或写入过程中的错误信息
	//
	// 设计意图：
	//   - 统一的格式化逻辑，确保所有生成的代码风格一致
	//   - 使用 go/format 包自动格式化，符合 Go 代码规范（gofmt 标准）
	//   - 支持多种输出方式（文件、内存、标准输出等），提高灵活性
	//
	// 为什么需要格式化？
	//   - AST 操作后生成的代码可能格式不统一
	//   - 自动格式化确保代码符合 Go 代码规范，提高可读性
	//   - 统一代码风格，避免因格式问题导致的代码审查困扰
	//
	// 好处：
	//   - 代码质量：自动格式化确保生成的代码符合规范
	//   - 一致性：所有生成的代码风格统一
	//   - 灵活性：支持多种输出方式，适应不同场景
	//   - 代码复用：Base 提供默认实现，子类可以按需重写
	Format(filename string, writer io.Writer, file *ast.File) error
}
