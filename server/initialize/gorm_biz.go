package initialize

import (
	"github.com/flipped-aurora/gin-vue-admin/server/global"
)

// bizModel 注册业务表（用户自定义的表）的自动迁移
//
// 设计思路：
// 将业务表的迁移逻辑与系统核心表的迁移逻辑分离，便于管理和维护
//
// 为什么单独创建这个函数？
// - 职责分离：系统表（RegisterTables）和业务表分开管理，代码结构更清晰
// - 动态扩展：业务表可能通过代码生成工具动态创建，需要独立的迁移入口
// - 便于维护：业务表迁移失败不影响系统表迁移的错误定位
// - 代码生成友好：代码生成工具可以自动向此函数注入业务模型的 AutoMigrate 调用
//
// 为什么使用 global.GVA_DB 而不是参数传递？
// - 简化调用：函数签名更简洁，调用方无需传递数据库连接
// - 全局一致性：使用全局数据库连接，与系统其他部分保持一致
// - 初始化阶段：在系统初始化阶段，全局数据库连接已经建立，可以直接使用
//
// 为什么 AutoMigrate() 没有参数？
// - 占位设计：这是一个占位函数，实际的业务模型会通过代码生成工具自动注入
// - 代码生成：utils/ast/package_initialize_gorm.go 会自动扫描并注入业务模型到 AutoMigrate 调用中
// - 灵活性：用户可以通过代码生成工具添加业务表，无需手动修改此函数
//
// 这样写的好处：
// - 自动化：代码生成工具可以自动管理业务表的迁移，减少手动维护成本
// - 可扩展：新增业务表时，代码生成工具会自动更新此函数
// - 安全性：业务表迁移失败会返回错误，由调用方决定如何处理（通常是退出程序）
// - 清晰性：系统表和业务表的迁移逻辑分离，便于理解和调试
func bizModel() error {
	// 获取全局数据库连接
	// 为什么使用全局变量而不是参数？
	// - 初始化阶段全局连接已建立，直接使用更简洁
	// - 与系统其他部分保持一致的设计模式
	db := global.GVA_DB

	// 执行业务表的自动迁移
	// 注意：此处的 AutoMigrate() 调用会被代码生成工具自动注入业务模型参数
	// 例如：db.AutoMigrate(&model.User{}, &model.Order{})
	// 如果没有业务表，此调用不会产生任何副作用（GORM 的 AutoMigrate 支持空参数）
	err := db.AutoMigrate()
	if err != nil {
		// 返回错误，由调用方处理
		// 为什么返回错误而不是直接退出？
		// - 错误处理统一：由 RegisterTables() 统一处理错误和日志记录
		// - 灵活性：调用方可以根据错误类型决定处理策略
		// - 可测试性：返回错误便于单元测试
		return err
	}
	return nil
}
