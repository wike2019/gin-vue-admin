package initialize

import (
	"github.com/flipped-aurora/gin-vue-admin/server/global"
	"go.uber.org/zap"
)

// Reload 优雅地重新加载系统配置
//
// 设计目的：
// 实现系统配置的热重载功能，无需重启服务即可应用新的配置。
// 这对于生产环境特别重要，可以避免服务中断，提高系统可用性。
//
// 为什么需要热重载功能？
// 1. 提高可用性：修改配置后无需重启服务，避免服务中断
//   - 生产环境重启服务会导致所有正在处理的请求失败
//   - 热重载可以在不中断服务的情况下应用新配置
//   - 用户体验更好，系统响应更及时
//
// 2. 快速响应配置变更：配置修改后立即生效
//   - 例如：修改数据库连接信息、JWT 过期时间、定时任务配置等
//   - 无需等待服务重启，配置变更立即生效
//   - 特别适合需要频繁调整配置的场景
//
// 3. 降低运维成本：减少人工干预
//   - 可以通过 API 接口触发重载，无需登录服务器
//   - 支持自动化运维脚本，实现配置变更的自动化
//   - 降低运维人员的工作负担
//
// 4. 支持灰度发布：可以逐步应用新配置
//   - 可以先在测试环境验证配置，再应用到生产环境
//   - 支持配置回滚，如果新配置有问题可以快速恢复
//
// 调用场景：
// - 通过 HTTP API 接口触发：POST /system/reloadSystem
// - 通过系统信号触发（未来扩展）
// - 通过配置文件监控自动触发（未来扩展）
//
// 设计原则：
// 1. 原子性：要么全部成功，要么全部失败，避免部分重载导致的不一致状态
// 2. 顺序性：按照依赖关系顺序重载，确保依赖项先于被依赖项重载
// 3. 错误处理：任何步骤失败都立即返回错误，不继续执行后续步骤
// 4. 资源清理：重载前先关闭旧资源，避免资源泄漏
func Reload() error {
	global.GVA_LOG.Info("正在重新加载系统配置...")

	// 第一步：重新加载配置文件
	// 为什么这是第一步？
	// - 配置文件是所有其他配置的基础，必须先加载
	// - 后续的数据库连接、JWT 配置等都依赖配置文件中的值
	// - 如果配置文件加载失败，后续步骤无法正确执行
	//
	// 为什么使用 ReadInConfig() 而不是重新创建 Viper 实例？
	// - 保持配置管理器的状态：Viper 实例可能包含其他配置信息
	// - 性能考虑：重新创建实例需要重新初始化，开销更大
	// - 兼容性：保持与现有代码的兼容，其他模块可能依赖 global.GVA_VP
	//
	// 为什么立即返回错误而不是继续执行？
	// - 配置加载失败意味着后续步骤无法正确执行
	// - 继续执行会导致使用错误的配置，可能造成数据损坏或安全问题
	// - 快速失败（fail-fast）原则：尽早发现并报告错误
	if err := global.GVA_VP.ReadInConfig(); err != nil {
		global.GVA_LOG.Error("重新读取配置文件失败!", zap.Error(err))
		return err
	}

	// 为什么需要 Unmarshal？
	// - ReadInConfig() 只是将配置文件内容读取到 Viper 的内存中
	// - 但 global.GVA_CONFIG 结构体并没有自动更新
	// - 后续代码（如 Gorm()、OtherInit() 等）都依赖 global.GVA_CONFIG 读取配置
	// - 如果不调用 Unmarshal，这些函数仍会使用旧的配置值，导致重载失败
	// - 这与 viper.go 中的 OnConfigChange 回调函数保持一致的处理方式
	if err := global.GVA_VP.Unmarshal(&global.GVA_CONFIG); err != nil {
		global.GVA_LOG.Error("重新解析配置文件到全局配置结构体失败!", zap.Error(err))
		return err
	}

	// 第二步：关闭旧的数据库连接
	// 为什么需要先关闭旧连接？
	// 1. 资源管理：避免连接泄漏
	//   - 数据库连接是有限资源，不关闭会导致连接池耗尽
	//   - 长时间运行的服务如果不断创建新连接而不关闭旧连接，会导致数据库连接数过多
	//   - 可能导致数据库拒绝新连接，影响系统可用性
	//
	// 2. 配置一致性：确保使用新配置建立连接
	//   - 旧连接使用的是旧配置，可能已经失效（如密码修改、IP 变更等）
	//   - 如果不关闭旧连接，新连接和旧连接可能同时存在，造成混乱
	//   - 关闭旧连接确保所有操作都使用新配置建立的连接
	//
	// 3. 事务安全：避免旧连接上的未提交事务影响新连接
	//   - 如果旧连接上有未提交的事务，关闭连接会回滚这些事务
	//   - 确保数据一致性，避免脏数据
	//
	// 为什么使用 if global.GVA_DB != nil 判断？
	// - 容错处理：如果数据库未初始化（首次启动或初始化失败），跳过关闭操作
	// - 避免空指针异常：直接调用 Close() 会导致 panic
	// - 支持部分重载：某些场景下可能只需要重载部分配置，不需要重载数据库
	//
	// 为什么使用 db, _ := global.GVA_DB.DB()？
	// - GORM 的 DB() 方法返回底层的 *sql.DB 实例，用于关闭连接
	// - 忽略第二个返回值（error）：如果 GORM 连接已经关闭，这里会返回错误，但不影响流程
	// - 使用底层 DB 的 Close() 方法可以确保连接池中的所有连接都被关闭
	if global.GVA_DB != nil {
		db, _ := global.GVA_DB.DB()
		err := db.Close()
		if err != nil {
			// 为什么关闭失败要返回错误？
			// - 关闭失败可能导致连接泄漏，影响系统稳定性
			// - 如果旧连接未关闭，后续创建新连接可能导致连接数过多
			// - 错误应该被记录和报告，让运维人员知道存在问题
			global.GVA_LOG.Error("关闭原数据库连接失败!", zap.Error(err))
			return err
		}
	}

	// 第三步：重新建立数据库连接
	// 为什么在关闭旧连接后立即建立新连接？
	// - 最小化服务中断时间：快速恢复数据库连接，减少对业务的影响
	// - 确保后续步骤可以使用数据库：RegisterTables() 等步骤需要数据库连接
	// - 原子性操作：关闭和重建应该作为一个整体，避免中间状态
	//
	// 为什么使用 Gorm() 函数而不是直接调用具体的数据库初始化函数？
	// - 配置驱动：Gorm() 会根据配置文件中的 DbType 自动选择对应的数据库类型
	// - 代码复用：不需要在这里重复数据库类型判断逻辑
	// - 一致性：与系统初始化时使用相同的逻辑，确保行为一致
	//
	// 为什么直接赋值给 global.GVA_DB？
	// - 覆盖旧连接：确保全局变量指向新的数据库连接
	// - 其他模块通过 global.GVA_DB 访问数据库，自动使用新连接
	// - 无需修改其他代码，实现透明的连接切换
	global.GVA_DB = Gorm()

	// 第四步：重新初始化其他配置
	// 为什么需要重新初始化其他配置？
	// - 配置可能已变更：JWT 过期时间、缓存配置等可能已修改
	// - 确保配置一致性：所有组件都使用最新的配置值
	// - 重新初始化缓存：BlackCache 的过期时间可能已变更，需要重新创建
	//
	// OtherInit() 的作用：
	// - 重新解析 JWT 配置（过期时间、缓冲时间等）
	// - 重新创建 BlackCache（使用新的过期时间配置）
	// - 重新检测 Go 模块名（如果配置变更）
	//
	// 为什么在数据库连接建立后调用？
	// - OtherInit() 不依赖数据库，但为了保持初始化顺序的一致性
	// - 如果未来 OtherInit() 需要数据库，顺序已经正确
	OtherInit()

	// 第五步：重新初始化数据库列表（多数据库支持）
	// 为什么需要重新初始化数据库列表？
	// - 配置可能已变更：可能新增、删除或修改了数据库配置
	// - 确保多数据库连接使用新配置：GVA_DBList 中存储的所有数据库连接都需要更新
	// - 支持动态添加数据库：可以在不重启服务的情况下添加新的数据库连接
	//
	// DBList() 的作用：
	// - 遍历配置文件中的所有数据库配置
	// - 为每个数据库创建新的连接
	// - 更新 global.GVA_DBList 映射表
	// - 更新 global.GVA_DB（如果存在系统数据库）
	//
	// 为什么在 OtherInit() 之后调用？
	// - DBList() 可能依赖 OtherInit() 中的某些配置（虽然当前不依赖，但为了保持顺序）
	// - 保持初始化顺序的一致性，便于理解和维护
	CloseDBList()
	DBList()

	// 第六步：重新注册数据库表（自动迁移）
	// 为什么需要重新注册表？
	// - 表结构可能已变更：模型定义可能已修改，需要同步到数据库
	// - 确保数据库结构最新：新添加的表、字段等需要创建
	// - 支持模型变更的热更新：修改模型后无需重启服务即可更新表结构
	//
	// 为什么使用 if global.GVA_DB != nil 判断？
	// - 容错处理：如果数据库连接建立失败，跳过表注册
	// - 避免空指针异常：RegisterTables() 内部会使用 global.GVA_DB
	// - 支持部分重载：某些场景下可能不需要重载数据库
	//
	// 为什么在 DBList() 之后调用？
	// - 确保数据库连接已建立：RegisterTables() 需要数据库连接
	// - 确保使用最新的数据库连接：DBList() 可能更新了 global.GVA_DB
	// - 依赖关系：表注册依赖于数据库连接，必须在连接建立后执行
	//
	// 设计考虑：
	// - 如果 DisableAutoMigrate 为 true，RegisterTables() 会跳过自动迁移
	// - 这是为了生产环境安全，防止意外修改数据库结构
	// - 重载时也会遵循这个配置，确保行为一致
	if global.GVA_DB != nil {
		// 确保数据库表结构是最新的
		RegisterTables()
	}
	//情况历史定时任务
	global.GVA_Timer.Reset()

	// 第七步：重新初始化定时任务
	// 为什么需要重新初始化定时任务？
	// - 定时任务配置可能已变更：cron 表达式、任务列表等可能已修改
	// - 确保定时任务使用新配置：新添加的任务需要注册，删除的任务需要移除
	// - 支持动态调整定时任务：可以在不重启服务的情况下修改定时任务配置
	//
	// Timer() 的作用：
	// - 停止旧的定时任务（如果支持）
	// - 使用新配置重新注册定时任务
	// - 更新定时任务管理器
	//
	// 为什么在最后调用？
	// - 定时任务可能依赖数据库连接：某些定时任务需要访问数据库
	// - 定时任务可能依赖其他配置：JWT、缓存等配置可能影响定时任务
	// - 确保所有依赖项都已重载完成，定时任务才能正确执行
	//
	// 设计考虑：
	// - Timer() 内部使用 goroutine 异步执行，不会阻塞重载流程
	// - 即使定时任务注册失败，也不会影响重载流程的完成
	// - 这是为了确保重载操作的原子性：配置重载和定时任务重载是分离的
	Timer()

	// 重载完成，记录成功日志
	// 为什么记录日志？
	// - 可追溯性：记录重载操作，便于问题排查和审计
	// - 监控告警：可以通过日志监控重载操作的频率和结果
	// - 用户反馈：前端可以通过日志确认重载操作是否成功
	global.GVA_LOG.Info("系统配置重新加载完成")
	return nil
}
