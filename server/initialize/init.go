// 系统事件处理器注册模块
//
// 设计目的：
// 将系统级事件（如配置重载、优雅关闭等）的处理逻辑注册到全局事件管理器，
// 实现事件驱动的架构模式，提高系统的灵活性和可维护性。

package initialize

import (
	"github.com/flipped-aurora/gin-vue-admin/server/utils"
)

// SetupHandlers 注册全局系统事件处理函数
//
// 为什么需要这个函数？
// 1. 解耦设计：将事件处理逻辑与事件触发机制分离
//   - 初始化模块只负责注册处理函数，不关心何时触发
//   - 其他模块（如 HTTP 接口、信号处理等）可以统一触发事件
//   - 符合单一职责原则，每个模块只做自己该做的事
//
// 2. 可扩展性：支持多个处理函数注册
//   - 不同模块可以注册自己的重载逻辑
//   - 例如：配置模块注册配置重载、路由模块注册路由重载
//   - 系统重载时会依次执行所有注册的处理函数
//
// 3. 统一管理：所有系统级事件集中管理
//   - 通过 GlobalSystemEvents 统一管理所有系统事件
//   - 便于监控和调试，可以统一查看所有注册的事件处理器
//   - 支持动态添加和移除事件处理器（未来扩展）
//
// 4. 支持热重载：无需重启服务即可重新加载配置
//   - 当配置文件修改后，可以通过 API 或信号触发重载
//   - 系统会调用所有注册的重载处理函数，重新初始化相关组件
//   - 提高系统可用性，减少服务中断时间
//
// 5. 线程安全：GlobalSystemEvents 内部使用互斥锁保护
//   - 支持并发环境下的安全注册和触发
//   - 多个 goroutine 可以安全地注册和触发事件
//
// 调用时机：
// - 在系统初始化完成后调用（main.go 的 initializeSystem 函数中）
// - 此时所有组件已初始化完成，可以安全地注册重载逻辑
//
// 设计模式：
// - 观察者模式（Observer Pattern）：事件管理器是主题，处理函数是观察者
// - 策略模式（Strategy Pattern）：不同的重载逻辑可以作为不同的策略注册
func SetupHandlers() {
	// 注册系统重载处理函数到全局事件管理器
	//
	// 为什么使用匿名函数包装 Reload()？
	// 1. 适配接口：RegisterReloadHandler 需要 func() error 类型的函数
	//    - Reload() 函数签名正好匹配，可以直接使用
	//    - 如果未来 Reload() 签名改变，只需在这里修改包装逻辑
	//
	// 2. 灵活性：可以在包装函数中添加额外的逻辑
	//    - 例如：添加日志记录、性能监控、错误处理等
	//    - 未来扩展时不需要修改 Reload() 函数本身
	//
	// 3. 清晰性：明确表达"将 Reload 函数注册为重载处理器"的意图
	//    - 代码可读性更好，一眼就能看出这是在注册重载逻辑
	utils.GlobalSystemEvents.RegisterReloadHandler(func() error {
		// 调用 Reload() 函数执行系统重载
		// Reload() 会重新加载配置、重建数据库连接、重新初始化定时任务等
		// 详见 initialize/reload.go 文件
		return Reload()
	})

	// 未来可以在这里注册其他系统事件处理函数，例如：
	// - 优雅关闭处理函数
	// - 配置变更通知处理函数
	// - 健康检查处理函数
	// 等等...
}
