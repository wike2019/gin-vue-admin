package system

import (
	"github.com/gin-gonic/gin"
)

// BaseRouter 基础功能路由结构体
//
// 设计说明：
// 1. 为什么使用结构体？
//   - 遵循面向对象设计原则，将基础功能路由的初始化逻辑封装在结构体方法中
//   - 便于代码组织和维护，基础功能相关的所有路由都有独立的结构体
//   - 符合 Go 语言的最佳实践，提高代码的可读性和可维护性
//   - 便于后续扩展，如果需要添加路由相关的配置或状态，可以直接在结构体中添加字段
//
// 2. 为什么使用空结构体？
//   - 这个结构体只用于方法绑定，不需要存储任何状态数据
//   - 空结构体不占用内存空间，性能最优
//   - 符合 Go 语言的惯用法，简洁高效
//
// 3. 好处：
//   - 代码结构清晰：基础功能相关的所有路由定义独立，便于查找和维护
//   - 易于扩展：未来如果需要添加基础功能相关的其他路由（如注册、找回密码等），只需在此方法中扩展
//   - 统一管理：所有基础功能相关的路由都在一个地方，避免路由分散
//   - 符合单一职责原则：每个路由结构体只负责一个功能模块的路由定义
type BaseRouter struct{}

// InitBaseRouter 初始化基础功能路由信息
//
// 设计说明：
// 1. 路由分组设计：
//   - 使用 Router.Group("base") 创建路由组，统一管理基础功能相关的所有接口
//   - 路由组路径为 "base"，访问路径为 /api/v1/base/xxx（具体路径取决于父路由组）
//   - 好处：所有基础功能相关的接口都有统一的前缀，便于管理和识别
//
// 2. 为什么这些路由不需要认证？
//   - login（登录）接口：用户登录前没有 token，无法进行认证，必须先允许访问登录接口
//   - captcha（验证码）接口：验证码在登录时使用，登录前就需要获取，因此也不应该需要认证
//   - 这些接口属于"公共接口"，任何用户（包括未登录用户）都应该能够访问
//
// 3. 代码块分组（{}）的作用：
//   - 代码组织：将相关的路由注册逻辑分组，提高可读性
//   - 作用域管理：代码块可以限制变量的作用域，避免命名冲突
//   - 逻辑清晰：每个代码块代表一个功能模块，便于理解和维护
//   - 便于注释：可以对整个代码块进行统一说明
//
// 4. 返回值的作用：
//   - 返回 gin.IRoutes 接口类型，便于链式调用或进一步处理
//   - 调用方可以获取已注册的路由组，用于添加中间件或其他操作
//   - 增加方法的灵活性，支持更复杂的路由配置场景
//
// 5. 路由设计：
//   - login（用户登录）：POST /base/login
//   - 为什么使用 POST：登录需要传递敏感信息（用户名、密码），POST 请求体更安全
//   - 为什么不使用 GET：GET 参数会出现在 URL 中，容易被日志记录，存在安全风险
//   - captcha（获取验证码）：POST /base/captcha
//   - 为什么使用 POST：虽然验证码获取看似是查询操作，但为了保持接口设计一致性
//   - 验证码通常与登录配合使用，使用相同的方法类型更符合 RESTful 设计原则
//
// @param Router *gin.RouterGroup 父路由组，通常是 PublicGroup（公共路由组，不需要认证）
// @return R gin.IRoutes 返回已配置的路由组，便于链式调用或进一步处理
func (s *BaseRouter) InitBaseRouter(Router *gin.RouterGroup) (R gin.IRoutes) {
	// 创建 "base" 路由组
	// 作用：统一管理基础功能相关的所有接口，所有接口路径都以 /base 开头
	// 好处：
	//   - 接口路径清晰，便于识别功能模块
	//   - 便于统一添加中间件（如果需要）
	//   - 符合 RESTful API 设计规范
	baseRouter := Router.Group("base")
	{
		// 用户登录接口
		// 路径：POST /base/login
		// 说明：处理用户登录请求，验证用户名、密码和验证码，成功后返回 JWT token
		// 为什么是公共接口：用户登录前没有 token，必须先允许访问登录接口
		baseRouter.POST("login", baseApi.Login)

		// 获取验证码接口
		// 路径：POST /base/captcha
		// 说明：生成图形验证码，返回验证码图片（base64）和验证码ID
		// 为什么是公共接口：验证码在登录时使用，登录前就需要获取
		// 安全性：验证码用于防止暴力破解和自动化攻击
		baseRouter.POST("captcha", baseApi.Captcha)
	}
	return baseRouter
}
