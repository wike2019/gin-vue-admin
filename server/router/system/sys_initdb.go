package system

import (
	"github.com/gin-gonic/gin"
)

// InitRouter 数据库初始化路由结构体
//
// 设计说明：
// 1. 为什么使用结构体？
//   - 遵循面向对象设计原则，将路由初始化逻辑封装在结构体方法中
//   - 便于代码组织和维护，每个功能模块的路由都有独立的结构体
//   - 符合 Go 语言的最佳实践，提高代码的可读性和可维护性
//   - 便于后续扩展，如果需要添加路由相关的配置或状态，可以直接在结构体中添加字段
//
// 2. 好处：
//   - 代码结构清晰：数据库初始化相关的所有路由定义独立，便于查找和维护
//   - 易于扩展：未来如果需要添加初始化相关的其他路由，只需在此方法中扩展
//   - 统一管理：所有初始化相关的路由都在一个地方，避免路由分散
//   - 符合单一职责原则：每个路由结构体只负责一个功能模块的路由定义
type InitRouter struct{}

// InitInitRouter 初始化数据库初始化相关路由
//
// 设计说明：
// 1. 路由分组设计：
//   - 使用 Router.Group("init") 创建路由组，统一管理数据库初始化相关的所有接口
//   - 路由组路径为 "init"，访问路径为 /api/v1/init/xxx
//   - 好处：所有初始化相关的接口都有统一的前缀，便于管理和识别
//
// 2. 为什么放在公共路由组（PublicGroup）？
//   - 数据库初始化通常在系统首次部署时进行，此时可能还没有管理员账户
//   - 如果放在私有路由组，需要 JWT 认证，但初始化时可能还没有用户数据
//   - 允许在未认证状态下完成系统初始化，避免"先有鸡还是先有蛋"的问题
//   - 安全考虑：初始化接口应该在生产环境禁用或添加额外保护（如 IP 白名单）
//
// 3. 为什么使用 POST 方法？
//   - initdb：初始化数据库会执行数据变更操作（创建表、插入初始数据等），属于写操作
//   - checkdb：虽然只是检查，但使用 POST 可以传递更复杂的参数，且语义上表示"执行检查动作"
//   - POST 方法支持请求体，可以传递初始化配置参数（如数据库连接信息、初始化选项等）
//   - 符合 RESTful 设计规范：写操作使用 POST，读操作使用 GET
//
// 4. 为什么使用代码块（{}）分组？
//   - 代码组织：将相关的路由注册逻辑分组，提高可读性
//   - 作用域管理：代码块可以限制变量的作用域，避免命名冲突
//   - 逻辑清晰：每个代码块代表一个功能模块，便于理解和维护
//
// 5. 设计优势：
//   - 模块化：初始化功能独立封装，不影响其他路由模块
//   - 可扩展性：未来可以轻松添加其他初始化相关的接口（如重置数据库、导入初始数据等）
//   - 安全性：虽然放在公共路由组，但可以在 API 层面添加额外的安全检查
//   - 可维护性：所有初始化相关的路由集中管理，便于后续维护和修改
//
// 参数说明：
//   - Router: 路由组，通常是 "/api/v1" 下的子路由组
//     对于初始化路由，通常传入 PublicGroup（公共路由组），允许未认证访问
func (s *InitRouter) InitInitRouter(Router *gin.RouterGroup) {
	// 创建数据库初始化相关的路由组
	// 为什么使用路由分组：
	//   - 统一管理初始化相关的所有接口，便于维护和识别
	//   - 所有初始化接口都有统一的前缀 /api/v1/init/xxx
	//   - 如果未来需要为初始化路由添加统一的中间件（如限流、日志等），只需在此处添加
	// 好处：
	//   1. 代码组织清晰：初始化相关的路由集中管理
	//   2. 易于扩展：添加新的初始化接口时，只需在此路由组下添加
	//   3. 统一配置：可以为所有初始化接口统一配置中间件或权限控制
	initRouter := Router.Group("init")
	{
		// 初始化数据库接口
		// 功能：执行数据库初始化操作，创建系统所需的表结构和初始数据
		// 为什么需要这个接口：
		//   - 系统首次部署时需要初始化数据库结构
		//   - 支持自动化部署流程，无需手动执行 SQL 脚本
		//   - 便于开发环境快速搭建和测试
		// 使用场景：
		//   - 系统首次安装时，前端会调用此接口完成数据库初始化
		//   - 开发环境重置数据库时使用
		//   - 自动化测试环境搭建时使用
		// 安全注意事项：
		//   - 此接口会清空并重建数据库，属于危险操作
		//   - 生产环境应该禁用此接口或添加额外的安全验证（如 IP 白名单、特殊密钥等）
		//   - 建议在配置文件中添加开关，控制是否允许初始化操作
		initRouter.POST("initdb", dbApi.InitDB) // 初始化数据库

		// 检测是否需要初始化数据库接口
		// 功能：检查数据库是否已初始化，返回初始化状态
		// 为什么需要这个接口：
		//   - 前端需要知道系统是否已完成初始化，决定是否显示初始化页面
		//   - 避免重复初始化，防止误操作导致数据丢失
		//   - 提供初始化状态查询，便于系统状态监控
		// 使用场景：
		//   - 系统启动时，前端调用此接口检查是否需要初始化
		//   - 用户访问系统时，根据初始化状态决定跳转到初始化页面还是登录页面
		// 设计优势：
		//   - 将检查和初始化分离，符合单一职责原则
		//   - 前端可以先检查状态，再决定是否执行初始化
		//   - 避免不必要的初始化操作，提高系统安全性
		initRouter.POST("checkdb", dbApi.CheckDB) // 检测是否需要初始化数据库
	}
}
