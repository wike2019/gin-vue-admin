// Package system 提供系统相关的路由定义
// 本文件专门负责自动代码生成历史记录功能的路由配置
// 
// 为什么需要历史记录功能？
// - 代码生成器会创建大量文件（API、Service、Model、Router等），如果生成错误需要回滚
// - 历史记录保存了生成时的元数据（表名、结构体名、模板信息等），支持精确回滚
// - 支持查看历史生成记录，便于追踪代码生成历史和审计
package system

import (
	"github.com/gin-gonic/gin"
)

// AutoCodeHistoryRouter 自动代码生成历史记录路由结构体
// 
// 设计说明：
// 1. 使用空结构体作为接收器：不占用内存空间，只用于方法分组和组织代码
// 2. 结构体命名规范：Router 后缀表明这是路由定义，与 Service、Api 层区分
// 3. 为什么使用结构体而非函数？
//    - 更好的封装性：可以将路由相关的状态和方法组织在一起
//    - 易于扩展：未来如果需要添加路由级别的中间件或配置，可以轻松扩展
//    - 符合 Go 的面向对象编程习惯：通过方法接收者实现功能分组
//    - 便于测试：可以针对结构体方法进行单元测试
//
// 注意：当前代码中 InitAutoCodeHistoryRouter 方法的接收者是 *AutoCodeRouter，
// 这可能是历史遗留问题，建议统一为 *AutoCodeHistoryRouter 以保持一致性
type AutoCodeHistoryRouter struct{}

// InitAutoCodeHistoryRouter 初始化自动代码生成历史记录相关的路由
// 
// 参数说明：
//   - Router: 需要认证的私有路由组，通常已绑定 JWT 认证中间件
//             历史记录操作涉及代码回滚等敏感操作，必须确保用户身份验证
//
// 设计优势：
// 1. 路由分组管理：使用 Router.Group("autoCode") 创建路由组
//    好处：
//    - 代码组织清晰：所有自动代码相关接口统一前缀为 /autoCode
//    - URL 结构统一：例如 /api/v1/autoCode/getMeta、/api/v1/autoCode/rollback
//    - 便于 API 版本管理：如果需要升级 API 版本，只需修改路由组前缀
//    - 路由中间件统一应用：可以在路由组级别统一应用中间件（如日志、限流等）
//
// 2. 使用代码块 {} 分组：将相关功能的路由分组
//    好处：
//    - 可读性：代码结构清晰，一眼就能看出这些路由属于历史记录功能模块
//    - 可维护性：新增或修改路由时，容易找到对应的功能模块
//    - 便于注释：可以为整个功能模块添加说明注释
//    - 作用域管理：代码块可以限制变量的作用域，避免命名冲突
//
// 3. 统一使用 POST 方法：所有接口都使用 POST 而非 GET
//    原因：
//    - 安全性：POST 请求体可以传递复杂参数（如回滚选项），GET 只能通过 URL 参数
//    - 数据量：历史记录查询可能涉及分页、筛选等复杂参数，POST 更适合
//    - 语义清晰：回滚、删除等操作虽然可以查询历史，但本质是有副作用的操作
//    - 一致性：与自动代码生成的其他接口保持一致（都使用 POST）
//
// 4. 功能模块划分：
//    - getMeta: 获取单条历史记录的元数据信息
//    - rollback: 回滚自动生成的代码（核心功能）
//    - delSysHistory: 删除历史记录（清理功能）
//    - getSysHistory: 获取历史记录列表（查询功能）
//    好处：
//    - CRUD 操作完整：支持查询、删除、回滚等完整操作
//    - 职责清晰：每个接口职责单一，便于维护和测试
//    - 符合 RESTful 设计思想：虽然使用 POST，但功能划分清晰
func (s *AutoCodeRouter) InitAutoCodeHistoryRouter(Router *gin.RouterGroup) {
	// 创建路由组：所有历史记录相关接口的前缀为 /autoCode
	// 完整路径示例：/api/v1/autoCode/getMeta
	// 为什么复用 "autoCode" 前缀？
	// - 历史记录是自动代码生成功能的子功能，属于同一业务域
	// - 保持 URL 结构的一致性，便于前端统一管理 API 路径
	// - 如果未来需要版本控制，可以统一升级整个 autoCode 路由组
	autoCodeHistoryRouter := Router.Group("autoCode")
	
	// ========== 自动代码生成历史记录管理模块 ==========
	// 功能：提供代码生成历史记录的查询、回滚、删除等操作
	// 权限：需要认证，因为涉及代码回滚等敏感操作，必须确保用户权限
	// 设计：统一使用 POST 方法，支持复杂参数传递
	{
		// 获取历史记录的元数据信息
		// 用途：根据历史记录 ID 获取生成时的完整元数据（表名、结构体名、模板信息等）
		// 使用场景：
		//   - 查看历史生成记录的详细信息
		//   - 回滚前预览将要回滚的内容
		//   - 基于历史记录重新生成代码
		// 为什么需要元数据？
		//   - 回滚时需要知道生成了哪些文件、在哪些位置
		//   - 元数据包含完整的生成配置，支持精确回滚
		autoCodeHistoryRouter.POST("getMeta", autocodeHistoryApi.First)         // 根据id获取meta信息
		
		// 回滚自动生成的代码
		// 用途：撤销之前通过代码生成器创建的文件和相关资源
		// 回滚内容：
		//   - 删除生成的代码文件（API、Service、Model、Router等）
		//   - 可选：删除关联的 API 路由注册
		//   - 可选：删除关联的菜单项
		//   - 可选：删除数据库表（如果生成时创建了表）
		// 为什么需要回滚功能？
		//   - 代码生成器可能生成错误的代码，需要快速撤销
		//   - 支持实验性生成：可以生成代码测试，不满意可以回滚
		//   - 降低使用风险：知道可以回滚，用户更愿意尝试代码生成功能
		autoCodeHistoryRouter.POST("rollback", autocodeHistoryApi.RollBack)     // 回滚
		
		// 删除历史记录
		// 用途：从数据库中删除指定的历史记录，不删除实际生成的代码文件
		// 使用场景：
		//   - 清理不再需要的历史记录
		//   - 删除误操作产生的历史记录
		//   - 定期清理旧的历史记录，保持数据库整洁
		// 注意：删除历史记录不会删除实际代码文件，如需删除代码请使用 rollback
		autoCodeHistoryRouter.POST("delSysHistory", autocodeHistoryApi.Delete)  // 删除回滚记录
		
		// 获取历史记录分页列表
		// 用途：分页查询所有代码生成历史记录
		// 功能：
		//   - 支持分页查询，避免一次性加载大量数据
		//   - 可以查看所有历史生成记录，便于追踪和审计
		//   - 支持筛选和排序（通过请求参数）
		// 为什么需要分页？
		//   - 随着使用时间增长，历史记录会越来越多
		//   - 分页查询提高性能，避免一次性加载大量数据
		//   - 提升用户体验，前端可以逐步加载数据
		autoCodeHistoryRouter.POST("getSysHistory", autocodeHistoryApi.GetList) // 获取回滚记录分页
	}
}
