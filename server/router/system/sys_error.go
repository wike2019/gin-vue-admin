package system

import (
	"github.com/flipped-aurora/gin-vue-admin/server/middleware"
	"github.com/gin-gonic/gin"
)

// SysErrorRouter 错误日志路由结构体
//
// 设计说明：
// 1. 为什么使用结构体？
//   - 遵循面向对象设计原则，将路由初始化逻辑封装在结构体方法中
//   - 便于代码组织和维护，错误日志相关的所有路由都有独立的结构体
//   - 符合 Go 语言的最佳实践，提高代码的可读性和可维护性
//   - 便于后续扩展，如果需要添加路由相关的配置或状态，可以直接在结构体中添加字段
//
// 2. 好处：
//   - 代码结构清晰：错误日志相关的所有路由定义独立，便于查找和维护
//   - 易于扩展：未来如果需要添加错误日志相关的其他路由，只需在此方法中扩展
//   - 统一管理：所有错误日志相关的路由都在一个地方，避免路由分散
//   - 符合单一职责原则：每个路由结构体只负责一个功能模块的路由定义
type SysErrorRouter struct{}

// InitSysErrorRouter 初始化错误日志路由信息
//
// 设计说明：
// 1. 路由分组设计：
//   - 使用 Router.Group("sysError") 创建路由组，统一管理错误日志相关的所有接口
//   - 路由组路径为 "sysError"，访问路径为 /api/v1/sysError/xxx
//   - 好处：所有错误日志相关的接口都有统一的前缀，便于管理和识别
//
// 2. 为什么区分三个不同的路由组？
//   - sysErrorRouter：需要记录操作日志的路由组，用于修改类操作（删除、更新、获取解决方案）
//   - sysErrorRouterWithoutRecord：不需要记录操作日志的路由组，用于查询类操作
//   - sysErrorRouterWithoutAuth：不需要认证的公开路由组，用于创建错误日志
//   - 这样设计的原因：
//     a. 修改类操作（删除、更新）涉及数据变更，需要审计追踪，记录操作历史
//     b. 查询类操作不改变数据状态，属于只读操作，通常不需要审计记录
//     c. 查询操作通常非常频繁，如果都记录会产生大量日志，占用存储空间
//     d. 创建错误日志接口需要支持无认证访问，因为错误日志通常由系统自动记录，不需要用户登录
//   - 好处：
//     1. 性能优化：查询操作不记录日志，减少系统负担和数据库写入压力
//     2. 存储优化：避免查询日志占用大量存储空间，节省成本
//     3. 日志清晰：只记录关键操作（增删改），便于后续分析和问题排查
//     4. 审计完整：所有数据变更操作都有完整记录，满足安全审计和合规要求
//     5. 灵活记录：支持系统自动记录错误日志，无需用户认证，适用于异常捕获和监控场景
//
// 3. 为什么使用 OperationRecord 中间件？
//   - OperationRecord 中间件用于记录操作日志，包括操作人、操作时间、操作内容等
//   - 对于修改类操作（删除、更新、获取解决方案），记录操作日志有以下好处：
//     a. 安全审计：可以追踪谁在什么时候做了什么操作，满足合规要求
//     b. 问题排查：出现问题时可以根据日志快速定位和复现
//     c. 责任追溯：可以明确操作责任人，便于问题追责
//     d. 历史记录：保留完整的操作历史，支持数据恢复和回滚
//
// 4. 为什么需要 PublicRouter（公开路由组）？
//   - PublicRouter 是不需要认证的公开路由组，用于创建错误日志的接口
//   - 这样设计的原因：
//     a. 系统自动记录：错误日志通常由系统异常捕获机制自动记录，不需要用户登录
//     b. 监控系统集成：外部监控系统或日志收集系统可以直接上报错误，无需认证
//     c. 降低系统负担：错误记录操作应该尽可能轻量，避免认证流程影响错误记录
//     d. 异常场景支持：系统异常时可能无法完成认证流程，公开接口确保错误能被记录
//   - 安全性保障：
//     a. 虽然不需要认证，但创建错误日志接口通常只接受系统内部调用
//     b. 可以通过 IP 白名单、请求签名等方式限制访问来源
//     c. 错误日志创建接口通常只写入数据，不涉及敏感信息读取
//
// 参数说明：
//   - Router: 需要认证的私有路由组，通常是 "/api/v1" 下的子路由组
//     用于需要登录才能访问的接口，保证数据安全性
//   - PublicRouter: 公开路由组，用于无需认证的公开接口
//     用于创建错误日志的接口，支持系统自动记录和监控系统集成
func (s *SysErrorRouter) InitSysErrorRouter(Router *gin.RouterGroup, PublicRouter *gin.RouterGroup) {
	// 创建需要记录操作的路由组
	// 为什么使用 OperationRecord 中间件：
	//   - 这些路由都是修改类操作（删除、更新、获取解决方案），涉及错误日志数据的变更
	//   - 错误日志的管理操作（删除、更新）需要审计追踪，记录操作历史
	//   - 获取解决方案虽然不直接修改数据，但属于管理操作，需要记录操作人
	// 好处：
	//   1. 可以追踪谁在什么时候删除了错误日志或更新了错误信息
	//   2. 出现问题时可以根据日志快速定位和复现
	//   3. 满足安全审计和合规要求
	//   4. 支持操作回滚，如果误操作可以快速恢复
	sysErrorRouter := Router.Group("sysError").Use(middleware.OperationRecord())

	// 创建不需要记录操作的路由组
	// 为什么单独创建一个路由组：
	//   - 查询类操作通常频繁且不需要审计记录
	//   - 错误日志查询操作（如获取错误详情、错误列表）在前端页面加载时会被频繁调用
	//   - 如果都记录会产生大量无意义的日志，占用存储空间
	//   - 减少数据库写入操作，提高系统性能
	// 好处：
	//   1. 性能优化：查询操作不记录日志，减少系统负担和数据库写入压力
	//   2. 存储优化：避免查询日志占用大量存储空间，节省成本
	//   3. 日志清晰：只记录关键操作，便于后续分析和排查
	//   4. 响应速度：减少中间件处理时间，提高接口响应速度
	sysErrorRouterWithoutRecord := Router.Group("sysError")

	// 创建不需要认证的公开路由组
	// 为什么使用 PublicRouter：
	//   - 创建错误日志的接口需要支持无认证访问
	//   - 错误日志通常由系统异常捕获机制自动记录，不需要用户登录
	//   - 支持外部监控系统或日志收集系统直接上报错误，无需认证
	//   - 降低系统负担：错误记录操作应该尽可能轻量，避免认证流程影响错误记录
	//   - 异常场景支持：系统异常时可能无法完成认证流程，公开接口确保错误能被记录
	// 安全性保障：
	//   1. 虽然不需要认证，但创建错误日志接口通常只接受系统内部调用
	//   2. 可以通过 IP 白名单、请求签名等方式限制访问来源
	//   3. 错误日志创建接口通常只写入数据，不涉及敏感信息读取
	// 好处：
	//   1. 系统集成：支持监控系统、日志收集系统等外部系统直接上报错误
	//   2. 异常处理：系统异常时仍能记录错误信息，不会因认证失败而丢失错误日志
	//   3. 性能优化：避免认证流程的开销，确保错误记录操作的快速响应
	//   4. 灵活性：支持多种错误记录场景，不局限于用户操作触发的错误
	sysErrorRouterWithoutAuth := PublicRouter.Group("sysError")

	{
		// 需要记录操作的修改类接口
		// 为什么这些接口需要记录：
		//   - 都是数据修改或管理操作，涉及错误日志的变更
		//   - 错误日志的删除和更新属于关键操作，需要追踪操作历史和责任人
		//   - 获取解决方案虽然不直接修改数据，但属于管理操作，需要记录操作人
		//   - 便于问题排查和安全审计
		sysErrorRouter.DELETE("deleteSysError", sysErrorApi.DeleteSysError)           // 删除错误日志 - 危险操作，必须完整记录
		sysErrorRouter.DELETE("deleteSysErrorByIds", sysErrorApi.DeleteSysErrorByIds) // 批量删除错误日志 - 批量操作，需要审计
		sysErrorRouter.PUT("updateSysError", sysErrorApi.UpdateSysError)              // 更新错误日志 - 数据修改，需要可追溯
		sysErrorRouter.GET("getSysErrorSolution", sysErrorApi.GetSysErrorSolution)    // 触发错误日志处理 - 管理操作，需要记录操作人
	}
	{
		// 不需要记录操作的查询类接口
		// 为什么这些接口不记录：
		//   - 查询操作不改变数据状态，属于只读操作
		//   - 查询操作通常非常频繁，记录会产生大量日志
		//   - 查询操作通常不需要审计追踪，只有修改操作才需要
		//   - 错误日志查询在前端页面加载时会被频繁调用，如果都记录会影响性能
		sysErrorRouterWithoutRecord.GET("findSysError", sysErrorApi.FindSysError)       // 根据ID获取错误日志 - 查询操作，不记录日志
		sysErrorRouterWithoutRecord.GET("getSysErrorList", sysErrorApi.GetSysErrorList) // 获取错误日志列表 - 查询操作，不记录日志
	}
	{
		// 不需要认证的公开接口（系统自动记录错误）
		// 为什么这些接口不需要认证：
		//   - 错误日志通常由系统异常捕获机制自动记录，不需要用户登录
		//   - 支持外部监控系统或日志收集系统直接上报错误，无需认证
		//   - 降低系统负担：错误记录操作应该尽可能轻量，避免认证流程影响错误记录
		//   - 异常场景支持：系统异常时可能无法完成认证流程，公开接口确保错误能被记录
		// 安全性说明：
		//   - 虽然不需要认证，但创建错误日志接口通常只接受系统内部调用
		//   - 可以通过 IP 白名单、请求签名等方式限制访问来源
		//   - 错误日志创建接口通常只写入数据，不涉及敏感信息读取
		sysErrorRouterWithoutAuth.POST("createSysError", sysErrorApi.CreateSysError) // 新建错误日志 - 公开接口，支持系统自动记录和监控系统集成
	}
}
