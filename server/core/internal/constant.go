package internal

// 配置文件相关的常量定义
//
// 设计思路：
// 1. 将配置相关的常量集中管理，避免在代码中硬编码字符串
// 2. 放在 internal 包中，限制外部包的直接访问，提高封装性
// 3. 统一命名规范，便于维护和查找
//
// 为什么使用常量而不是硬编码字符串：
// - 可维护性：如果需要修改配置文件名，只需修改一处，所有引用自动更新
// - 避免错误：编译期就能发现拼写错误，而不是运行时才发现
// - 代码可读性：使用有意义的常量名，代码更清晰易懂
// - IDE 支持：IDE 可以自动补全和重构，提高开发效率
//
// 为什么放在 internal 包中：
// - 封装性：internal 包只能被父目录的包导入，防止外部包直接访问内部实现细节
// - 稳定性：内部常量变更不会影响外部包的 API，降低破坏性变更的风险
// - 清晰性：明确标识这些是内部使用的常量，不是对外暴露的 API
const (
	// ConfigEnv 环境变量名称，用于通过环境变量指定配置文件路径
	//
	// 使用场景：
	// - 容器化部署（Docker、Kubernetes）：通过环境变量注入配置文件路径
	// - CI/CD 流程：不同环境使用不同的配置文件路径
	// - 多实例部署：同一代码库在不同环境使用不同配置
	//
	// 好处：
	// 1. 配置与代码分离：符合 12-Factor App 原则，配置通过环境变量注入
	// 2. 灵活性：不修改代码即可切换配置文件，适合 DevOps 实践
	// 3. 安全性：敏感配置可以通过环境变量传递，避免硬编码在代码中
	// 4. 可移植性：同一份代码可以在不同环境运行，只需设置不同的环境变量
	//
	// 使用示例：
	//   export GVA_CONFIG=/path/to/production-config.yaml
	//   ./server
	ConfigEnv = "GVA_CONFIG"

	// ConfigDefaultFile 默认配置文件名称
	//
	// 用途：
	// - 作为兜底方案，当没有指定其他配置文件时使用
	// - 适用于简单的开发环境或单环境部署
	//
	// 好处：
	// 1. 容错性：即使环境变量或运行模式未设置，也能找到配置文件
	// 2. 简化部署：新环境不需要准备多个配置文件，使用默认配置即可
	// 3. 向后兼容：老项目可能只有这一个配置文件，仍能正常运行
	ConfigDefaultFile = "config.yaml"

	// ConfigTestFile 测试环境配置文件名称
	//
	// 用途：
	// - 当 Gin 运行在 TestMode 时自动使用此配置文件
	// - 通常包含测试数据库连接、模拟服务配置等
	//
	// 好处：
	// 1. 环境隔离：测试环境使用独立的配置，不会影响开发和生产环境
	// 2. 自动化：通过设置 GIN_MODE=test 自动选择测试配置，无需手动指定
	// 3. 安全性：测试配置可以使用测试数据库，避免误操作生产数据
	//
	// 使用场景：
	// - 单元测试、集成测试
	// - CI/CD 自动化测试流程
	ConfigTestFile = "config.test.yaml"

	// ConfigDebugFile 调试/开发环境配置文件名称
	//
	// 用途：
	// - 当 Gin 运行在 DebugMode 时自动使用此配置文件
	// - 通常包含详细的日志配置、调试开关、开发数据库连接等
	//
	// 好处：
	// 1. 开发友好：开发环境自动启用详细日志和调试功能，提高开发效率
	// 2. 性能隔离：开发环境的性能配置（如日志级别）不影响生产环境
	// 3. 安全性：开发配置可以使用开发数据库，避免误操作生产数据
	//
	// 典型配置内容：
	// - 日志级别：DEBUG（生产环境通常是 INFO 或 WARN）
	// - 数据库：开发数据库（与生产数据库隔离）
	// - 调试开关：启用 SQL 日志、请求日志等
	ConfigDebugFile = "config.debug.yaml"

	// ConfigReleaseFile 生产环境配置文件名称
	//
	// 用途：
	// - 当 Gin 运行在 ReleaseMode 时自动使用此配置文件
	// - 通常包含生产环境的优化配置、安全设置等
	//
	// 好处：
	// 1. 性能优化：生产环境默认使用优化配置（如关闭调试日志）
	// 2. 安全性：生产配置通常包含更严格的安全设置
	// 3. 稳定性：生产环境使用稳定的配置，避免开发配置中的实验性功能
	// 4. 自动化：通过设置 GIN_MODE=release 自动选择生产配置
	//
	// 典型配置内容：
	// - 日志级别：INFO 或 WARN（减少日志量，提高性能）
	// - 数据库：生产数据库连接池配置
	// - 安全设置：启用 HTTPS、CORS 限制等
	// - 性能优化：连接池大小、超时时间等
	ConfigReleaseFile = "config.release.yaml"
)
