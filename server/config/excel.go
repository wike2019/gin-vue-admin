package config

// Excel Excel文件处理配置结构体
// 用于配置Excel文件的导入导出功能，支持数据的批量导入和导出
// 设计目的：
// 1. 数据导入：支持从Excel文件批量导入数据到系统
// 2. 数据导出：支持将系统数据导出为Excel文件
// 3. 报表生成：生成各种业务报表的Excel文件
// 4. 数据交换：与其他系统进行数据交换
// 使用场景：
// - 用户批量导入：批量导入用户、商品等数据
// - 数据导出：导出订单、报表等数据供分析
// - 模板下载：提供Excel模板供用户填写
type Excel struct {
	// Dir Excel文件存储目录：Excel文件的存储路径
	// 格式：绝对路径或相对路径，例如 "/var/www/excel" 或 "./uploads/excel"
	// 设计目的：
	// 1. 文件管理：集中存储Excel文件，便于管理和清理
	// 2. 临时存储：存储导入导出的临时Excel文件
	// 3. 模板存储：存储Excel模板文件
	// 注意事项：
	// 1. 确保目录存在且有读写权限
	// 2. 建议使用绝对路径，避免相对路径带来的问题
	// 3. 定期清理临时文件，避免磁盘空间耗尽
	// 4. 生产环境应考虑文件访问权限和安全性
	Dir string `mapstructure:"dir" json:"dir" yaml:"dir"`
}
